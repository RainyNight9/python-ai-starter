"""
app.agent 包：演示「AI Agent」中最核心的能力之一 —— 工具调用（Tool / Function Calling）。

---------------------------------------------------------------------------
为什么需要这个包？
---------------------------------------------------------------------------
普通聊天接口只把「用户说的话 + 历史」发给模型，模型只能「凭空」回答。
Agent 范式则允许模型在需要时**主动请求执行外部工具**（计算器、查时间、
调业务 API 等），后端真实执行后再把结果喂回模型，形成「思考 → 行动 →
再思考」的闭环。这是现代 AI 应用（助手、自动化、RAG+检索后处理等）的基础。

---------------------------------------------------------------------------
本仓库中的职责划分（便于你阅读源码）
---------------------------------------------------------------------------
- tool_definitions：把「工具有哪些、参数长什么样」声明成模型能看懂的 JSON Schema。
- tools：每个工具背后的 Python 实现（真正干活的地方）。
- ../services/agent_service.py：编排「多轮对话 + 多次工具调用」的循环逻辑。

注意：Agent 接口默认走「非流式」完整回合，便于你在网络面板里对照每一步
请求/响应；流式 Agent 可作为后续进阶练习自行扩展。
"""
